// Derives the server's per-module completion requirements from the same content
// files the browser uses, so seat time and required videos can never drift apart.
// Usage: node scripts/generate-requirements.mjs [--check]
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'netlify', 'lib', 'module-requirements.mjs');
const sources = ['js/modules-1-6.js', 'js/modules-7-13.js', 'js/video-library.js'];

export async function buildRequirements() {
  const code = (await Promise.all(sources.map(file => readFile(path.join(root, file), 'utf8')))).join('\n');
  const context = {};
  new vm.Script(`${code}\nthis.modules = MODULES; this.videos = REQUIRED_VIDEOS;`).runInNewContext(context);
  const requirements = {};
  for (const module of context.modules) {
    const videos = {};
    for (const video of context.videos.filter(item => item.moduleId === module.id)) {
      videos[video.id] = video.durationSeconds;
    }
    // seconds is the self-paced seat time; an instructor-led session covers the rest of
    // the module's credited hours once the instructor signs it off.
    const instructorMinutes = module.instructorLed?.minutes || 0;
    requirements[module.id] = { seconds: Math.round(module.hours * 3600 - instructorMinutes * 60), videos };
    if (module.instructorLed) requirements[module.id].instructorLed = { key: module.instructorLed.key, minutes: instructorMinutes };
  }
  return requirements;
}

export function renderRequirements(requirements) {
  const lines = Object.entries(requirements).map(([id, { seconds, videos, instructorLed }]) =>
    `  ${id}: { seconds: ${seconds}, videos: ${JSON.stringify(videos)}${instructorLed ? `, instructorLed: ${JSON.stringify(instructorLed)}` : ''} }`);
  return [
    '// GENERATED by scripts/generate-requirements.mjs from js/modules-*.js and js/video-library.js.',
    '// Do not edit by hand: run `pnpm run requirements` after changing module hours or required videos.',
    'export const MODULE_REQUIREMENTS = {',
    lines.join(',\n'),
    '};',
    ''
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const rendered = renderRequirements(await buildRequirements());
  if (process.argv.includes('--check')) {
    const current = await readFile(outFile, 'utf8').catch(() => '');
    if (current !== rendered) {
      console.error('netlify/lib/module-requirements.mjs is out of date. Run `pnpm run requirements` and commit the result.');
      process.exit(1);
    }
    console.log('Server module requirements match the client content.');
  } else {
    await writeFile(outFile, rendered, 'utf8');
    console.log(`Wrote ${path.relative(root, outFile)}`);
  }
}
